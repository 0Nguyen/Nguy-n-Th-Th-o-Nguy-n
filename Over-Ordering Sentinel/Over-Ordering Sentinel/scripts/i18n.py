def get_language() -> str:
    selector_label = st.session_state.get("language_selector")
    if selector_label in SUPPORTED_LANGUAGES.values():
        reverse_map = {label: code for code, label in SUPPORTED_LANGUAGES.items()}
        lang = reverse_map.get(selector_label, DEFAULT_LANGUAGE)
        st.session_state["language"] = lang
        return lang
    lang = st.session_state.get("language", DEFAULT_LANGUAGE)
    if lang not in SUPPORTED_LANGUAGES:
        lang = DEFAULT_LANGUAGE
    st.session_state["language"] = lang
    return lang


def set_language(lang: str) -> None:
    if lang not in SUPPORTED_LANGUAGES:
        lang = DEFAULT_LANGUAGE
    st.session_state["language"] = lang


def t(key: str, **kwargs) -> str:
    lang = get_language()
    text = TRANSLATIONS.get(lang, {}).get(key)
    if text is None:
        text = TRANSLATIONS["vi"].get(key, key)
    try:
        return text.format(**kwargs)
    except Exception:
        return text
